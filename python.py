        "    self.embedding = nn.Embedding(vocab_size, n_embed)\n",
        "    self.positional_encoding = nn.Embedding(context_size, n_embed)\n",
        "    self.transformer = Transformer(num_head, n_embed)\n",
        "    self.lm_head = nn.Linear(n_embed, vocab_size)\n",
