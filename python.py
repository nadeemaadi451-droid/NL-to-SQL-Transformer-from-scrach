        "  def embed(self, ids):\n",
        "    pos = torch.arange(ids.shape[1], device=ids.device)\n",
        "    return self.embedding(ids) + self.positional_encoding(pos)\n",
        "\n",
        "  def forward(self, src, dec_in, targets=None):\n",
        "    src_mask = (src != Pad_id)\n",
        "    x = self.transformer(self.embed(src), self.embed(dec_in), src_mask)\n",
        "    logits = self.lm_head(x)                      # keep [B, T, C]\n",
        "    if targets is None:\n",
